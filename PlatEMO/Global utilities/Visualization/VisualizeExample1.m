                p1_final_objs(1), p1_final_objs(2), ...
                'SizeData', 140, ...
                'CData', final_color, ...
                'Marker', '^', ...
                'MarkerFaceColor', 'none', ...
                'MarkerEdgeColor', final_color, ...
                'LineWidth', 3);
        end
    end
    uistack(h_PF, 'bottom');
    
    % Add legend
    legend([h_PF, h_ref, h_n, h_fX0, h_ifX0, h_fX1, h_ifX1, h_GSA], ...
        {'True Pareto Set', ...
        'Reference Point', ...
        'Neighbors', ...
        'Feasible Solutions ($X_0$)', ...
        'Infeasible Solutions ($X_0$)', ...
